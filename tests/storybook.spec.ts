import { test, expect } from '@playwright/test'

test('繪本首頁顯示本機 Huninn、目的地插圖與可編輯資料的航班卡片', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(255, 252, 246)')
  await expect(page.locator('.sendai-story')).toBeVisible()
  await expect(page.getByRole('img', { name: /仙台繪本/ })).toBeVisible()
  await expect(page.locator('.story-fox')).toHaveCount(3)
  await expect(page.locator('.flight-card')).toHaveCount(2)
  await expect(page.locator('.flight-outbound')).toContainText('JX862')
  await page.evaluate(() => document.fonts.ready)
  expect(await page.evaluate(() => document.fonts.check('16px Huninn'))).toBe(true)
  await page.getByRole('link', { name: '編輯旅行資料' }).click()
  await page.getByLabel('去程航班', { exact: true }).fill('測試航班｜個人修改仍保留')
  await page.getByRole('navigation', { name: '主導覽' }).getByRole('link', { name: '行程 Itinerary', exact: true }).click()
  await expect(page.locator('.flight-outbound')).toContainText('測試航班｜個人修改仍保留')
  await page.reload()
  await expect(page.locator('.flight-outbound')).toContainText('測試航班｜個人修改仍保留')
})

test('日期彈跳、狐狸、楓葉與飄雪遵循減少動態效果，飄雪設定可保存', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  await expect(page.locator('.snow-layer')).toHaveCount(0)
  await expect(page.locator('.story-fox').first()).toHaveCSS('animation-name', 'fox-peek')
  await page.getByRole('button', { name: /DAY 2 / }).click()
  await expect(page.locator('.day-summary')).toHaveCSS('animation-name', 'day-bounce')
  await page.getByLabel('繪本飄雪', { exact: false }).check()
  await expect(page.locator('.snow-layer > span')).toHaveCount(6)
  await expect(page.locator('.snow-layer')).toHaveCSS('pointer-events', 'none')
  await page.reload()
  await expect(page.getByLabel('繪本飄雪', { exact: false })).toBeChecked()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('.snow-layer')).toHaveCSS('display', 'none')
  await expect(page.locator('.maple-layer')).toHaveCount(0)
  await expect(page.locator('.story-fox').first()).toHaveCSS('animation-name', 'none')
  await expect(page.locator('.day-summary')).toHaveCSS('animation-name', 'none')
})
